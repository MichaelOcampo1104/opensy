def define_lateral_loads(gm_dir: Path) -> None:
    """Define 3-dir UniformExcitation from ground_motions/*.txt (factor 5).

    Args:
        gm_dir: Folder holding GM1X.txt, GM1Y.txt, GM1Z.txt.
    """
    ops.timeSeries(
        "Series", PAT_GM_X, "-dt", DT_GM / sec,
        "-filePath", str(gm_dir / GM_FILE_X), "-factor", GM_FACTOR,
    )
    ops.pattern("UniformExcitation", PAT_GM_X, 1, "-accel", PAT_GM_X)
    ops.timeSeries(
        "Series", PAT_GM_Y, "-dt", DT_GM / sec,
        "-filePath", str(gm_dir / GM_FILE_Y), "-factor", GM_FACTOR,
    )
    ops.pattern("UniformExcitation", PAT_GM_Y, 2, "-accel", PAT_GM_Y)
    ops.timeSeries(
        "Series", PAT_GM_Z, "-dt", DT_GM / sec,
        "-filePath", str(gm_dir / GM_FILE_Z), "-factor", GM_FACTOR,
    )
    ops.pattern("UniformExcitation", PAT_GM_Z, 3, "-accel", PAT_GM_Z)

# ── 12. ANALYSIS ─────────────────────────────────────────────────────────────
def apply_rayleigh_damping() -> None:
    """Rayleigh damping, 2% on modes 1–2 (verbatim eigen-based computation)."""
    lam = ops.eigen(N_EIGEN)
    om_i = lam[0] ** 0.5
    om_j = lam[1] ** 0.5
    alpha_m = DAMP_RATIO * 2.0 * om_i * om_j / (om_i + om_j)
    beta_k = 2.0 * DAMP_RATIO / (om_i + om_j)
    ops.rayleigh(alpha_m, beta_k, 0.0, 0.0)

def run_dynamic(odb: "opst.post.CreateODB") -> None:
    """Run the 2000-step transient (Newmark 0.5/0.25) via SmartAnalyze.

    Args:
        odb: Active CreateODB instance; fetch_response_step() throttled
            to every ODB_EVERY_N steps (500 fetches total).
    """
    ops.constraints("Transformation")
    ops.numberer("RCM")
    ops.system("BandGeneral")
    ops.integrator("Newmark", 0.5, 0.25)   # set BEFORE SmartAnalyze
    analysis = opst.anlys.SmartAnalyze(
        analysis_type="Transient",
        tryAlterAlgoTypes=True,
        algoTypes=[40, 10, 20, 30, 50],
        tryAddTestTimes=True,
        testIterTimesMore=[50, 100],
        relaxation=0.5,
        minStep=1.0e-6,
    )
    segs = analysis.transient_split(N_STEPS)
    for i, _ in enumerate(segs):
        ok = analysis.TransientAnalyze(DT_ANALYSIS / sec)
        if ok < 0:
            break
        if i % ODB_EVERY_N == 0:
            odb.fetch_response_step()
    analysis.close()

def run_analysis(output_dir: Path) -> "opst.post.CreateODB":
    """Build model, apply 3-dir excitation, return populated ODB.

    Args:
        output_dir: Directory for ODB files and HTML output.

    Returns:
        The populated CreateODB instance.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    opst.post.set_odb_path(str(output_dir))
    gm_dir = Path(__file__).parent / "ground_motions"
    init_model()
    define_materials()
    define_sections()
    define_nodes()
    define_boundary_conditions()
    vis_nodes(output_dir)                           # V1: nodes + supports
    define_elements()
    vis_model(output_dir)                           # V2: full geometry
    odb = create_odb(output_dir)
    define_gravity_loads()
    define_lateral_loads(gm_dir)
    vis_loads(output_dir)                           # V3: load vectors
    vis_pre_analysis(output_dir)                    # V4: pre-analysis check
    apply_rayleigh_damping()
    run_dynamic(odb)
    return odb

# ── 13. POST-PROCESSING ──────────────────────────────────────────────────────
def post_process(odb: "opst.post.CreateODB", output_dir: Path) -> None:
    """Flush ODB to disk and render deformed-shape HTML.

    Args:
        odb: Populated CreateODB returned by run_analysis().
        output_dir: Folder where ODB and HTML files are written.
    """
    odb.save_response()
    vis_defo(output_dir, filename="vis_05_deformed.html", odb_tag=ODB_TAG, resp_dof="UX")
    vis_slider(output_dir, filename="vis_06_slider.html", odb_tag=ODB_TAG, resp_dof="UX")

